using System;

namespace mailTester.Mail
{
    public static class DiagnosticAdvice
    {
        public static string For(CheckFinding f, string domain = null)
        {
            switch (f.Section)
            {
                case "SPF":
                    return "Проверьте реальные исходящие IP и всех провайдеров отправки. Один TXT v=spf1 на MAIL FROM-домен. Пример (НЕ копировать без замены): v=spf1 ip4:<IP> include:<провайдер> -all. Уберите дубликаты, +all и ненужные include; проверьте каждый реальный IP. Для домена, который точно не отправляет почту: v=spf1 -all.";
                case "DKIM":
                    return "Включите DKIM-подписание на отправляющем MTA. Опубликуйте выданный сервером публичный ключ в TXT <selector>._domainkey (или CNAME по инструкции провайдера); RSA 2048 бит либо поддерживаемый Ed25519. Закрытый ключ не публикуется. Проверьте d=/s= на реальном EML, после ротации оставьте старый ключ до окончания доставки.";
                case "DMARC":
                    return (f.Summary.Contains("не обнаружена", StringComparison.OrdinalIgnoreCase) ? "Опубликуйте DMARC после проверки SPF/DKIM. " :
                        f.Summary.Contains("наследуется", StringComparison.OrdinalIgnoreCase) ? "Сначала определите, нужна ли отдельная политика поддомена; не заменяйте наследуемую запись автоматически. " :
                        f.Summary.Contains("FAIL", StringComparison.OrdinalIgnoreCase) ? "Проверьте alignment: MAIL FROM или d= должны совпадать с From-доменом по выбранному режиму. " : "") +
                        "RFC 9989: проверьте авторский и организационный домены через DNS Tree Walk. Создайте ящик для отчётов, затем TXT _dmarc: v=DMARC1; p=none; rua=mailto:dmarc@" + (domain ?? "<домен>") + " (пример, адрес должен существовать). После анализа отчётов и выравнивания SPF/DKIM переходите p=quarantine, затем p=reject. При необходимости задайте sp/np, adkim/aspf. pct устарел: не рассчитывайте на выборочное применение; t=y запрашивает тестовый режим: reject → quarantine, quarantine → none; реализация получателя может отличаться. psd=n применяйте только на подтверждённой организационной границе, чтобы не наследовать чужую политику; psd=y предназначен для PSD. Для внешнего rua нужна авторизация получателя.";
                case "MX":
                    return "Сверьте MX с настройками провайдера, приоритеты и A/AAAA имён MX. Не используйте CNAME в качестве цели MX. Null MX (0 .) допустим только для домена без входящей почты.";
                case "PTR":
                    return "У владельца IP запросите PTR на имя исходящего MTA. A/AAAA этого имени должны возвращать тот же IP; сверяйте с EHLO.";
                case "DNSBL":
                    return "Проверьте конкретный список и его правила. Устраните причину (открытый relay, скомпрометированный аккаунт, вредоносный трафик) перед запросом delisting. PBL может обозначать политику провайдера, а не спам.";
                case "TLS":
                    return "Проверьте цепочку CA, SAN/имя узла, срок, часы системы и SNI. Продлите сертификат, установите цепочку и перезагрузите/перечитайте конфигурацию службы; проверяйте тот же порт и режим.";
                case "RDAP":
                case "WHOIS":
                    return "Сверьте expiration/paid-till и статусы с кабинетом регистратора. Включите автопродление и уведомления за 30/14/7 дней. Дата реестра не доказывает, что счёт у регистратора оплачен.";
                default:
                    return f.Level == CheckLevel.Error ? "Проверьте резолвер, доступность DNS и настройки записи у владельца зоны." : "Сверьте запись с конфигурацией соответствующей службы.";
            }
        }
    }
}
